test('CLI writes once, cannot overwrite input/output, and rejects unknown commands', () => {
  const dir = mkdtempSync(join(tmpdir(), 'snapshot-offline-test-'));
  try {
    const b = fixture();
    const backup = join(dir, 'backup.json');
    const e = join(dir, 'evidence.json');
    const out = join(dir, 'plan.json');
    writeFileSync(backup, JSON.stringify(b));
    writeFileSync(e, JSON.stringify(evidence(b)));
    const cli = join(__dirname, 'rehearsal.cjs');
    const run = (...args) => spawnSync(process.execPath, [cli, ...args], { encoding: 'utf8' });
    assert.equal(run('plan', backup, e, out).status, 0);
    assert.equal(JSON.parse(readFileSync(out, 'utf8')).operations.length, 2);
    assert.notEqual(run('plan', backup, e, out).status, 0);
    assert.notEqual(run('plan', backup, e, backup).status, 0);
    assert.equal(readFileSync(backup, 'utf8'), JSON.stringify(b));
    assert.notEqual(run('execute', backup, e, out).status, 0);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
