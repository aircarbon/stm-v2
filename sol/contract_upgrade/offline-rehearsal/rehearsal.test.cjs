function evidence(backup, block = '100') {
  const digest = sha256(JSON.stringify(backup));
  return {
    schemaVersion: 1,
    environment: 'rehearsal',
    entityId: '7',
    chainId: '31337',
    network: 'synthetic-fixture',
    contractAddress: addr(999),
    block: { number: block, hash: `0x${block === '100' ? 'a' : 'b'}`.padEnd(66, '0') },
    backupSha256: digest,
    scopeAccounts: [addr(2), addr(3)],
  };
}
function planned(backup = fixture()) {
  const e = evidence(backup);
  return plan(backup, e, e.backupSha256);
}
// Explicit expected snapshots; not generated by the implementation's burn plan.
function burned(complete = true) {
  const after = fixture();
  after.data.globalSecTokens = [{ ...after.data.ledgers[1].tokens[0], currentQty: '0' }];
  after.data.ledgers[1].tokens = [];
  after.data.ledgers[1].spot_sumQty = '0';
  after.data.ledgers[1].spot_sumQtyBurned = '7';
  if (complete) {
    after.data.globalSecTokens.push({ ...after.data.ledgers[2].tokens[0], currentQty: '0' });
    after.data.ledgers[2].tokens = [];
    after.data.ledgers[2].spot_sumQty = '0';
    after.data.ledgers[2].spot_sumQtyBurned = '13';
  }
  after.data.secTokenBurnedQty = complete ? '20' : '7';
  after.data.batches[0].burnedQty = complete ? '20' : '7';
  after.ledgerHash = 'new-native-hash';
  return after;
}
function checked(after, before = fixture()) {
  const pre = evidence(before);
  const post = evidence(after, '101');
  return verify(before, pre, pre.backupSha256, after, post, post.backupSha256);
}
function mapping(backup = burned()) {
  return {
    schemaVersion: 1,
    backupSha256: evidence(backup).backupSha256,
    path: "m/44'/60'/0'/0",
    addressCount: 10,
    entries: Array.from({ length: 10 }, (_, index) => ({
      index,
      oldAddress: addr(index + 1),
      newAddress: addr(index + 101),
    })),
    preservedAddresses: [],
  };
}
function mapped(backup = burned(), m = mapping(backup)) {
  const e = evidence(backup);
  return remap(backup, e, e.backupSha256, m);
}

test('plans only exact scoped tokens with deterministic evidence-bound IDs', () => {
  const result = planned();
  assert.deepEqual(
    result.operations.map(({ account, stId, quantity }) => ({ account, stId, quantity })),
    [
      { account: addr(2), stId: '2', quantity: '7' },
      { account: addr(3), stId: '3', quantity: '13' },
    ],
  );
  assert.deepEqual(planned(), result);
  const b = fixture();
  const e = evidence(b, '101');
  assert.notEqual(plan(b, e, e.backupSha256).operations[0].id, result.operations[0].id);
});

