test('reports exact completed/pending operations and accepts repeated evidence', () => {
  const partial = checked(burned(false));
  const ops = planned().operations;
  assert.equal(partial.complete, false);
  assert.deepEqual(partial.completed, [ops[0].id]);
  assert.deepEqual(partial.pending, [ops[1].id]);
  const full = checked(burned());
  assert.equal(full.complete, true);
  assert.deepEqual(
    full.completed,
    ops.map((op) => op.id),
  );
  assert.deepEqual(checked(burned()), full);
  const b = fixture();
  const e = evidence(b);
  assert.equal(verify(b, e, e.backupSha256, b, e, e.backupSha256).completed.length, 0);
});

